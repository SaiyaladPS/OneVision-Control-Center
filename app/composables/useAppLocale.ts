export function useAppLocale() {
  const storedLocale = useCookie<AppLocale>('onevision-locale', { default: () => 'th' })
  const locale = useState<AppLocale>('onevision-locale', () => storedLocale.value)
  const ready = useState('onevision-locale-ready', () => false)

  const setLocale = (next: AppLocale) => {
    locale.value = next
    storedLocale.value = next
    if (import.meta.client) {
      localStorage.setItem('onevision-locale', next)
      document.documentElement.lang = next
    }
  }

  if (import.meta.client && !ready.value) {
    const saved = localStorage.getItem('onevision-locale') as AppLocale | null
    if (saved && saved in messages) {
      locale.value = saved
      storedLocale.value = saved
    }
    document.documentElement.lang = locale.value
    ready.value = true
  }

  const t = (key: string, values: Record<string, string | number> = {}) => {
    let text = messages[locale.value][key] || messages.en[key] || key
    Object.entries(values).forEach(([name, value]) => {
      text = text.replaceAll(`{${name}}`, String(value))
    })
    return text
  }

  return {
    locale,
    locales: ['th', 'lo', 'en'] as AppLocale[],
    setLocale,
    t
  }
}
